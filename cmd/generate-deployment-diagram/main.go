// Command generate-deployment-diagram generates the state diagram of the
// automated server deployment from the state machine definition.
package main

import (
	"fmt"
	"os"

	provisioningServer "github.com/FuturFusion/operations-center/internal/provisioning/server"
)

const (
	outputPath = "doc/development/server-deployment-states.md"

	preamble = `<!-- Code generated by generate-deployment-diagram; DO NOT EDIT. -->

`
)

func main() {
	err := run()
	if err != nil {
		fmt.Fprintf(os.Stderr, "generate-deployment-diagram: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	diagram, err := provisioningServer.DeploymentStateDiagram()
	if err != nil {
		return err
	}

	return os.WriteFile(outputPath, []byte(preamble+diagram), 0o644)
}
