// Command generate-filtered-architecture-def writes a reduced arch file for the
// overview graph. The strict arch file stays the source of truth.
package main

import (
	"errors"
	"fmt"
	"os"

	"go.yaml.in/yaml/v4"
)

const (
	inputPath  = ".go-arch-lint.yml"
	outputPath = ".go-arch-lint-overview_gen.yml"

	preamble = `# Code generated by generate-filtered-architecture-def; DO NOT EDIT.
# Graph input only. Do not use this file for checks.

`
)

func main() {
	err := run()
	if err != nil {
		fmt.Fprintf(os.Stderr, "generate-filtered-architecture-def: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	in, err := os.ReadFile(inputPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", inputPath, err)
	}

	var arch map[string]any
	err = yaml.Unmarshal(in, &arch)
	if err != nil {
		return fmt.Errorf("parse %s: %w", inputPath, err)
	}

	err = reduce(arch)
	if err != nil {
		return fmt.Errorf("reduce %s: %w", inputPath, err)
	}

	out, err := yaml.Marshal(arch)
	if err != nil {
		return fmt.Errorf("marshal overview: %w", err)
	}

	err = os.WriteFile(outputPath, append([]byte(preamble), out...), 0o600)
	if err != nil {
		return fmt.Errorf("write %s: %w", outputPath, err)
	}

	return nil
}

// reduce removes the self references from each dependency rule. It fails
// when the arch file does not have the shape that the graphs need. A silent
// skip would write an unfiltered overview.
func reduce(arch map[string]any) error {
	deps, ok := arch["deps"].(map[string]any)
	if !ok {
		return errors.New(`"deps" is missing or not a map`)
	}

	for name, value := range deps {
		rule, ok := value.(map[string]any)
		if !ok {
			return fmt.Errorf("deps.%s: expected a map, got %T", name, value)
		}

		list, ok := rule["mayDependOn"].([]any)
		if !ok {
			return fmt.Errorf("deps.%s.mayDependOn: expected a list, got %T", name, rule["mayDependOn"])
		}

		list, err := filterList(list, name)
		if err != nil {
			return fmt.Errorf("deps.%s.mayDependOn: %w", name, err)
		}

		if len(list) == 0 {
			delete(rule, "mayDependOn")
		} else {
			rule["mayDependOn"] = list
		}

		// The validator rejects empty rule objects.
		if len(rule) == 0 {
			delete(deps, name)
		}
	}

	return nil
}

// filterList returns the names without self. It fails on a non-string entry.
func filterList(names []any, self string) ([]any, error) {
	out := make([]any, 0, len(names))
	for _, n := range names {
		name, ok := n.(string)
		if !ok {
			return nil, fmt.Errorf("expected a string, got %T", n)
		}

		if name == self {
			continue
		}

		out = append(out, n)
	}

	return out, nil
}
