package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

const (
	loggerPkgPath  = modulePath + "/internal/util/logger"
	metricsPkgPath = modulePath + "/internal/util/metrics"
)

func Test_collectComponents(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string

		assertErr require.ErrorAssertionFunc
		want      map[string][]string
	}{
		{
			name: "qualified calls are keyed by the called package",
			files: map[string]string{
				"internal/api/component.go": `package api

import (
	"github.com/FuturFusion/operations-center/internal/util/logger"
	"github.com/FuturFusion/operations-center/internal/util/metrics"
)

var (
	logAPI     = logger.RegisterComponent("api")
	metricsAPI = metrics.RegisterComponent("api.requests")
)
`,
			},

			assertErr: require.NoError,
			want: map[string][]string{
				loggerPkgPath:  {"api"},
				metricsPkgPath: {"api.requests"},
			},
		},
		{
			name: "aliased import",
			files: map[string]string{
				"internal/api/component.go": `package api

import m "github.com/FuturFusion/operations-center/internal/util/metrics"

var metricsAPI = m.RegisterComponent("api")
`,
			},

			assertErr: require.NoError,
			want: map[string][]string{
				metricsPkgPath: {"api"},
			},
		},
		{
			name: "unqualified call inside the target package",
			files: map[string]string{
				"internal/util/metrics/runtime.go": `package metrics

var componentRuntime = RegisterComponent("runtime")
`,
			},

			assertErr: require.NoError,
			want: map[string][]string{
				metricsPkgPath: {"runtime"},
			},
		},
		{
			name: "sorted and without duplicates",
			files: map[string]string{
				"internal/b/b.go": `package b

import "github.com/FuturFusion/operations-center/internal/util/logger"

var (
	one = logger.RegisterComponent("b")
	two = logger.RegisterComponent("a")
)
`,
				"internal/a/a.go": `package a

import "github.com/FuturFusion/operations-center/internal/util/logger"

var one = logger.RegisterComponent("b")
`,
			},

			assertErr: require.NoError,
			want: map[string][]string{
				loggerPkgPath: {"a", "b"},
			},
		},
		{
			name: "calls of other packages are not reported",
			files: map[string]string{
				"internal/other/other.go": `package other

import "example.com/other/logger"

var (
	one = logger.RegisterComponent("other")
	two = RegisterComponent("other")
	three = logger.Register("other")
)
`,
			},

			assertErr: require.NoError,
			want:      map[string][]string{},
		},
		{
			name: "test files and skipped directories",
			files: map[string]string{
				"internal/api/component_test.go": `package api

import "github.com/FuturFusion/operations-center/internal/util/logger"

var one = logger.RegisterComponent("test")
`,
				"e2e_tests/helpers.go": `package e2e

import "github.com/FuturFusion/operations-center/internal/util/logger"

var one = logger.RegisterComponent("e2e")
`,
				"doc/readme.txt": "not go",
			},

			assertErr: require.NoError,
			want:      map[string][]string{},
		},
		{
			name: "error - name is not a string literal",
			files: map[string]string{
				"internal/api/component.go": `package api

import "github.com/FuturFusion/operations-center/internal/util/logger"

const name = "api"

var one = logger.RegisterComponent(name)
`,
			},

			assertErr: func(t require.TestingT, err error, msgAndArgs ...any) {
				require.ErrorContains(t, err, "component.go:7", msgAndArgs...)
			},
			want: nil,
		},
		{
			name: "error - invalid go file",
			files: map[string]string{
				"internal/api/component.go": "not go",
			},

			assertErr: require.Error,
			want:      nil,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			// Setup
			root := t.TempDir()

			for name, content := range tc.files {
				path := filepath.Join(root, name)

				require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
				require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
			}

			// Run test
			got, err := collectComponents(root)

			// Assert
			tc.assertErr(t, err)
			require.Equal(t, tc.want, got)
		})
	}
}

func Test_render(t *testing.T) {
	tests := []struct {
		name       string
		intro      string
		components []string

		want string
	}{
		{
			name:       "one group",
			intro:      "Intro.\n",
			components: []string{"runtime"},

			want: `<!-- Code generated by generate-components; DO NOT EDIT. -->

Intro.

runtime:

- ` + "`runtime`" + `
`,
		},
		{
			name:       "grouped by top level",
			intro:      "Intro.\n",
			components: []string{"api", "daemon", "daemon.task", "daemon.task.refresh"},

			want: `<!-- Code generated by generate-components; DO NOT EDIT. -->

Intro.

api:

- ` + "`api`" + `

daemon:

- ` + "`daemon`" + `
- ` + "`daemon.task`" + `
- ` + "`daemon.task.refresh`" + `
`,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := render(tc.intro, tc.components)

			require.Equal(t, tc.want, string(got))
		})
	}
}
