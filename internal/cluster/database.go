package cluster

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"time"

	cowsqllogging "github.com/cowsql/go-cowsql/cluster/logging"
	cowsqlDriver "github.com/cowsql/go-cowsql/driver"
	incustls "github.com/lxc/incus/v7/shared/tls"

	clusterRepo "github.com/FuturFusion/operations-center/internal/cluster/repo/sqlite"
	"github.com/FuturFusion/operations-center/internal/sql/cowsql"
	"github.com/FuturFusion/operations-center/internal/sql/dbschema"
	dbdriver "github.com/FuturFusion/operations-center/internal/sql/sqlite"
)

// OpenLocalDB opens the database of this member in the database directory of varRoot.
func OpenLocalDB(ctx context.Context, varRoot *os.Root) (*clusterRepo.LocalDB, error) {
	err := varRoot.MkdirAll("database", 0o700)
	if err != nil {
		return nil, fmt.Errorf("Failed to create database directory: %w", err)
	}

	dir := filepath.Join(varRoot.Name(), "database")

	db, err := dbdriver.Open(dir)
	if err != nil {
		return nil, fmt.Errorf("Failed to open sqlite database: %w", err)
	}

	_, err = dbschema.EnsureLocal(ctx, db.DB, dir, dbschema.LocalUpdates(), dbschema.LocalFreshSchema())
	if err != nil {
		return nil, err
	}

	return &clusterRepo.LocalDB{DB: db.DB}, nil
}

// FindOrGenCertInfo returns the keypair stored as certFilename and keyFilename in varRoot, generating a self-signed one if there is none.
func FindOrGenCertInfo(varRoot *os.Root, certFilename string, keyFilename string) (*incustls.CertInfo, error) {
	// The certificate is generated by path and read through the root.
	err := incustls.FindOrGenCert(filepath.Join(varRoot.Name(), certFilename), filepath.Join(varRoot.Name(), keyFilename), false, true)
	if err != nil {
		return nil, err
	}

	certPEM, err := varRoot.ReadFile(certFilename)
	if err != nil {
		return nil, fmt.Errorf("Failed to read certificate %q: %w", certFilename, err)
	}

	keyPEM, err := varRoot.ReadFile(keyFilename)
	if err != nil {
		return nil, fmt.Errorf("Failed to read key %q: %w", keyFilename, err)
	}

	return incustls.KeyPairFromRaw(certPEM, keyPEM)
}

// OpenGlobalDB opens the global database through the gateway of membership. It also returns the database with [cowsql.ErrSomeNodesAreBehind].
func OpenGlobalDB(ctx context.Context, membership MembershipService, isClustered bool, clusterAddress string) (*cowsql.GlobalDB, error) {
	contextTimeout := 30 * time.Second
	if !isClustered {
		// This is a workaround for https://github.com/canonical/lxd/issues/5234. We set a very
		// high timeout when we're not clustered, since there's
		// actually no networking involved.
		contextTimeout = time.Minute
	}

	options := []cowsqlDriver.Option{
		cowsqlDriver.WithDialFunc(membership.Gateway().DialFunc()),
		cowsqlDriver.WithConnectionTimeout(10 * time.Second), //nolint:staticcheck
		cowsqlDriver.WithLogFunc(cowsqllogging.CowsqlLog),
		cowsqlDriver.WithContextTimeout(contextTimeout), //nolint:staticcheck
	}

	dir := filepath.Dir(membership.Gateway().Node().GlobalDatabaseDir())

	return cowsql.Open(ctx, "db.bin", membership.Gateway().NodeStore(), clusterAddress, dir, 36*time.Hour, options...)
}
